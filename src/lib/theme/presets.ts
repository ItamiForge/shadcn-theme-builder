import {
  DEFAULT_DARK,
  DEFAULT_LIGHT,
  ensureThemeColors,
  type ThemeAxes,
  type ThemeColors,
} from "./schema";

export type ThemePreset = {
  id: string;
  name: string;
  label: string;
  light: ThemeColors;
  dark: ThemeColors;
} & Partial<ThemeAxes>;

const baseLight = ensureThemeColors(DEFAULT_LIGHT);
const baseDark = ensureThemeColors(DEFAULT_DARK);

const withSidebar = (palette: ThemeColors): ThemeColors =>
  ensureThemeColors({
    ...palette,
    sidebar: palette.card,
    sidebarForeground: palette.cardForeground,
    sidebarPrimary: palette.primary,
    sidebarPrimaryForeground: palette.primaryForeground,
    sidebarAccent: palette.accent,
    sidebarAccentForeground: palette.accentForeground,
    sidebarBorder: palette.border,
    sidebarRing: palette.ring,
  });

/** Build a full light palette from surface + brand accents. */
function lightPalette(
  overrides: Partial<ThemeColors> &
    Pick<ThemeColors, "background" | "foreground" | "primary" | "primaryForeground">,
): ThemeColors {
  const bg = overrides.background;
  const fg = overrides.foreground;
  return withSidebar(
    ensureThemeColors({
      ...baseLight,
      card: overrides.card ?? bg,
      cardForeground: overrides.cardForeground ?? fg,
      popover: overrides.popover ?? overrides.card ?? bg,
      popoverForeground: overrides.popoverForeground ?? fg,
      secondary: overrides.secondary ?? "0.94 0.01 100",
      secondaryForeground: overrides.secondaryForeground ?? fg,
      muted: overrides.muted ?? "0.94 0.01 100",
      mutedForeground: overrides.mutedForeground ?? "0.45 0.02 100",
      accent: overrides.accent ?? overrides.secondary ?? "0.94 0.01 100",
      accentForeground: overrides.accentForeground ?? fg,
      destructive: overrides.destructive ?? "0.55 0.22 25",
      destructiveForeground: overrides.destructiveForeground ?? "0.99 0 0",
      border: overrides.border ?? "0.88 0.01 100",
      input: overrides.input ?? overrides.border ?? "0.88 0.01 100",
      ring: overrides.ring ?? overrides.primary,
      chart1: overrides.chart1 ?? overrides.primary,
      chart2: overrides.chart2 ?? overrides.accent ?? overrides.primary,
      chart3: overrides.chart3 ?? "0.55 0.12 180",
      chart4: overrides.chart4 ?? "0.7 0.14 80",
      chart5: overrides.chart5 ?? "0.6 0.16 320",
      ...overrides,
    }),
  );
}

function darkPalette(
  overrides: Partial<ThemeColors> &
    Pick<ThemeColors, "background" | "foreground" | "primary" | "primaryForeground">,
): ThemeColors {
  const fg = overrides.foreground;
  return withSidebar(
    ensureThemeColors({
      ...baseDark,
      card: overrides.card ?? "0.2 0.02 260",
      cardForeground: overrides.cardForeground ?? fg,
      popover: overrides.popover ?? overrides.card ?? "0.2 0.02 260",
      popoverForeground: overrides.popoverForeground ?? fg,
      secondary: overrides.secondary ?? "0.28 0.02 260",
      secondaryForeground: overrides.secondaryForeground ?? fg,
      muted: overrides.muted ?? "0.28 0.02 260",
      mutedForeground: overrides.mutedForeground ?? "0.7 0.02 260",
      accent: overrides.accent ?? overrides.secondary ?? "0.28 0.02 260",
      accentForeground: overrides.accentForeground ?? fg,
      destructive: overrides.destructive ?? "0.65 0.2 22",
      destructiveForeground: overrides.destructiveForeground ?? "0.99 0 0",
      border: overrides.border ?? "1 0 0 / 12%",
      input: overrides.input ?? "1 0 0 / 16%",
      ring: overrides.ring ?? overrides.primary,
      chart1: overrides.chart1 ?? overrides.primary,
      chart2: overrides.chart2 ?? overrides.accent ?? overrides.primary,
      chart3: overrides.chart3 ?? "0.7 0.12 180",
      chart4: overrides.chart4 ?? "0.75 0.14 80",
      chart5: overrides.chart5 ?? "0.68 0.16 320",
      ...overrides,
    }),
  );
}

